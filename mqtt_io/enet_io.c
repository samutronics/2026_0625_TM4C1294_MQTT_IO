//
// Convert one ASCII hex character to its 4-bit value.  Used by the OTA chunk
// decoder below; the web UI keeps its own copy in common/webui.c.
//
static uint8_t
HexNibble(char c)
{
    if((c >= '0') && (c <= '9')) { return((uint8_t)(c - '0')); }
    if((c >= 'a') && (c <= 'f')) { return((uint8_t)(c - 'a' + 10)); }
    if((c >= 'A') && (c <= 'F')) { return((uint8_t)(c - 'A' + 10)); }
    return(0);
}




